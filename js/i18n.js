// Current language
let currentLanguage = 'en';

// Function to change language
function changeLanguage(lang) {
    if (!translations[lang]) {
        console.error(`Language ${lang} not supported`);
        return;
    }
    
    currentLanguage = lang;
    
    // Update all translatable elements
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Handle special cases for different element types
            if (element.tagName === 'INPUT' && element.type === 'placeholder') {
                element.placeholder = translations[lang][key];
            } else if (element.tagName === 'INPUT' && (element.type === 'submit' || element.type === 'button')) {
                element.value = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
    
    // Store language preference
    localStorage.setItem('preferredLanguage', lang);
    
    // Update language selector
    const languageSelector = document.getElementById('language-selector');
    if (languageSelector) {
        languageSelector.value = lang;
    }
}

// Initialize language based on stored preference or browser language
document.addEventListener('DOMContentLoaded', function() {
    // Check for stored language preference
    const storedLanguage = localStorage.getItem('preferredLanguage');
    
    if (storedLanguage && translations[storedLanguage]) {
        currentLanguage = storedLanguage;
    } else {
        // Check browser language
        const browserLang = navigator.language || navigator.userLanguage;
        const shortLang = browserLang.split('-')[0];
        
        if (translations[shortLang]) {
            currentLanguage = shortLang;
        }
    }
    
    // Set initial language
    changeLanguage(currentLanguage);
    
    // Set up language selector
    const languageSelector = document.getElementById('language-selector');
    if (languageSelector) {
        languageSelector.value = currentLanguage;
        languageSelector.addEventListener('change', function() {
            changeLanguage(this.value);
        });
    }
});

// Export for use in other scripts
if (typeof module !== 'undefined' && module.exports) {
    module.exports = {
        changeLanguage,
        getCurrentLanguage: () => currentLanguage
    };
}
